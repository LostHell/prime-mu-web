UPDATE `MarketplaceListing` AS listing
INNER JOIN (
  SELECT
    id,
    ASCII(SUBSTRING(itemHex, 1, 1)) AS b0,
    FLOOR((
      ASCII(SUBSTRING(itemHex, 1, 1))
      + IF(ASCII(SUBSTRING(itemHex, 8, 1)) & 128, 256, 0)
    ) / 32) AS grp,
    (
      ASCII(SUBSTRING(itemHex, 1, 1))
      + IF(ASCII(SUBSTRING(itemHex, 8, 1)) & 128, 256, 0)
    ) MOD 32 AS idx,
    (ASCII(SUBSTRING(itemHex, 2, 1)) >> 3) & 15 AS lvl
  FROM `MarketplaceListing`
  WHERE itemName IS NULL
    AND LENGTH(itemHex) >= 10
) AS decoded ON decoded.id = listing.id AND decoded.b0 <> 255
LEFT JOIN `MarketplaceItemName` AS item
  ON item.grp = decoded.grp AND item.idx = decoded.idx
LEFT JOIN `MarketplaceBoxOfLuckName` AS box
  ON decoded.grp = 14 AND decoded.idx = 11 AND box.lvl = decoded.lvl
SET listing.itemName = CASE
  WHEN decoded.grp = 14 AND decoded.idx = 11 THEN COALESCE(box.name, 'Unknown item')
  ELSE COALESCE(item.name, 'Unknown item')
END;

